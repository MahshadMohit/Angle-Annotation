def compute_rcca_bifurcation(coord_dict, img, skeleton_3d, output_path, arm_dist=25):
    """
    Computes the RCCA bifurcation angle for given slices and coordinates.

    Parameters:
    - coord_dict: Dictionary containing slice indices as keys and (row, col) coordinates as values.
    - img: The main image object containing spacing information.
    - skeleton_3d: The 3D skeletonized volume.
    - output_path: Path where the output image will be saved.
    - arm_dist: Distance to trace along the branches.

    Returns:
    - results: List of dictionaries containing computation results for each slice.
    - best: Dictionary containing the details of the slice with the maximum angle.
    """

    spacing_arr = np.array(img.GetSpacing())[::-1]
    spacing_yx = (spacing_arr[1], spacing_arr[2])


    def get_two_branches(skel_slice, vertex_rc, arm=25):
        vy, vx = vertex_rc
        neighbors = []
        for dy in [-1, 0, 1]:
            for dx in [-1, 0, 1]:
                if dy == 0 and dx == 0:
                    continue
                ny, nx = vy + dy, vx + dx
                if 0 <= ny < skel_slice.shape[0] and 0 <= nx < skel_slice.shape[1]:
                    if skel_slice[ny, nx] > 0:
                        neighbors.append((ny, nx))

        if len(neighbors) < 2:
            return None, None

        branch_paths = []
        for start in neighbors[:2]:
            path = [(vy, vx), start]
            visited = {(vy, vx), start}
            curr = start

            for _ in range(arm):
                nbs = []
                cy, cx = curr
                for dy in [-1, 0, 1]:
                    for dx in [-1, 0, 1]:
                        if dy == 0 and dx == 0:
                            continue
                        ny, nx = cy + dy, cx + dx
                        if (ny, nx) not in visited:
                            if 0 <= ny < skel_slice.shape[0] and 0 <= nx < skel_slice.shape[1]:
                                if skel_slice[ny, nx] > 0:
                                    nbs.append((ny, nx))
                if not nbs:
                    break
                curr = nbs[0]
                visited.add(curr)
                path.append(curr)

            branch_paths.append(path)

        if len(branch_paths) < 2:
            return None, None

        return branch_paths[0], branch_paths[1]

    def angle_between_branches(vertex_rc, branch1, branch2, sp_yx):
        vy, vx = vertex_rc
        v_mm = np.array([vy * sp_yx[0], vx * sp_yx[1]])
        e1 = np.array([branch1[-1][0] * sp_yx[0], branch1[-1][1] * sp_yx[1]])
        e2 = np.array([branch2[-1][0] * sp_yx[0], branch2[-1][1] * sp_yx[1]])
        vec1 = e1 - v_mm
        vec2 = e2 - v_mm
        n1, n2 = np.linalg.norm(vec1), np.linalg.norm(vec2)
        if n1 < 1e-6 or n2 < 1e-6:
            return np.nan
        cos_a = np.clip(np.dot(vec1, vec2) / (n1 * n2), -1, 1)
        return float(np.degrees(np.arccos(cos_a)))


    print("=" * 55)
    print(f"  RCCA Bifurcation Angle Calculation for {len(coord_dict)} Slices")
    print("=" * 55)

    results = []

    for sl_idx, vertex in coord_dict.items():
        skel_sl = skeleton_3d[sl_idx]

        result = get_two_branches(skel_sl, vertex, arm=arm_dist)

        if result[0] is None or result[1] is None:
            print(f"  Slice {sl_idx}:  Two branches not found")
            results.append({
                "Slice": sl_idx, "Vertex_row": vertex[0],
                "Vertex_col": vertex[1], "Angle_deg": np.nan,
                "b1": None, "b2": None,
            })
            continue

        b1, b2 = result
        angle = angle_between_branches(vertex, b1, b2, spacing_yx)

        print(f"  Slice {sl_idx}: vertex=({vertex[0]},{vertex[1]})  →  Angle = {angle:.1f}°")
        results.append({
            "Slice": sl_idx,
            "Vertex_row": vertex[0],
            "Vertex_col": vertex[1],
            "Angle_deg": round(angle, 2),
            "b1": b1,
            "b2": b2,
        })

    valid = [r for r in results if not np.isnan(r["Angle_deg"])]
    if valid:
        best = max(valid, key=lambda r: r["Angle_deg"])
        print("-" * 55)
        print(f"   Best Slice: {best['Slice']} with Angle {best['Angle_deg']:.1f}°")
    else:
        print(" No valid angles found")
        best = None


    num_slices = len(results)
    cols_n = 6
    rows_n = int(np.ceil(num_slices / cols_n))

    fig, axes = plt.subplots(rows_n, cols_n, figsize=(cols_n * 3.5, rows_n * 3.5))
    axes = axes.flatten()

    for i, r in enumerate(results):
        ax = axes[i]
        sl = r["Slice"]
        vy = r["Vertex_row"]
        vx = r["Vertex_col"]

        pad = 60
        r_lo = max(0, vy - pad); r_hi = min(skeleton_3d[sl].shape[0], vy + pad)
        c_lo = max(0, vx - pad); c_hi = min(skeleton_3d[sl].shape[1], vx + pad)

        ax.imshow(skeleton_3d[sl][r_lo:r_hi, c_lo:c_hi], cmap='gray',
                  extent=[c_lo, c_hi, r_hi, r_lo])

        angle = r["Angle_deg"]

        if not np.isnan(angle) and r["b1"] is not None:
            b1_arr = np.array(r["b1"])
            b2_arr = np.array(r["b2"])
            ax.plot(b1_arr[:, 1], b1_arr[:, 0], '-', color='limegreen', lw=2, label='Branch 1')
            ax.plot(b2_arr[:, 1], b2_arr[:, 0], '-', color='orange', lw=2, label='Branch 2')
            ax.scatter([vx], [vy], c='red', s=120, zorder=6, marker='*')

            is_best = (best is not None and sl == best["Slice"])
            title_color = 'gold' if is_best else 'white'
            star = " " if is_best else ""
            ax.set_title(f"Slice {sl}{star}\n{angle:.1f}°",
                         fontsize=10, fontweight='bold', color=title_color)
        else:
            ax.set_title(f"Slice {sl}\n Failed", fontsize=10, color='red')

        ax.set_xlim(c_lo, c_hi); ax.set_ylim(r_hi, r_lo)
        ax.axis('off')

    for j in range(num_slices, len(axes)):
        axes[j].axis('off')

    best_info = f"Slice {best['Slice']} | {best['Angle_deg']:.1f}°" if best else "Not Found"
    plt.suptitle(f"RCCA Bifurcation Angle\nBest: {best_info}",
                 fontsize=13, fontweight='bold')
    plt.tight_layout()

    out_png = os.path.join(output_path, f"RCCA_bifurcation_{num_slices}slices.png")
    plt.savefig(out_png, dpi=200, bbox_inches='tight')
    plt.show()
    print(f"\n Image saved: {out_png}")

    return results, best

