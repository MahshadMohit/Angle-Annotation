def compute_bifurcation_angles(skeleton_3d, coordinates_dict, spacing_yx,
                                arm_dist=25, output_path=None, vessel_name="Vessel"):

    def get_two_branches(skel_slice, vertex_rc, arm=25):
        vy, vx = vertex_rc

        # all neighbors of vertex
        all_neighbors = []
        for dy in [-1, 0, 1]:
            for dx in [-1, 0, 1]:
                if dy == 0 and dx == 0:
                    continue
                ny, nx = vy+dy, vx+dx
                if 0 <= ny < skel_slice.shape[0] and 0 <= nx < skel_slice.shape[1]:
                    if skel_slice[ny, nx] > 0:
                        all_neighbors.append((ny, nx))

        if len(all_neighbors) < 2:
            return None, None

        # --- KEY FIX: only keep neighbors going UPWARD (row < vertex row) ---
        upward = [n for n in all_neighbors if n[0] < vy]

        # if fewer than 2 upward neighbors, relax to same row too
        if len(upward) < 2:
            upward = [n for n in all_neighbors if n[0] <= vy]

        # still fewer than 2 — fall back to all neighbors
        if len(upward) < 2:
            upward = all_neighbors

        # from upward candidates, pick the pair farthest apart
        if len(upward) < 2:
            return None, None

        max_dist  = -1
        best_pair = (upward[0], upward[1])
        for ii in range(len(upward)):
            for jj in range(ii+1, len(upward)):
                d = np.linalg.norm(
                    np.array(upward[ii]) - np.array(upward[jj])
                )
                if d > max_dist:
                    max_dist  = d
                    best_pair = (upward[ii], upward[jj])

        selected = list(best_pair)

        branch_paths = []
        for start in selected:
            path    = [(vy, vx), start]
            visited = {(vy, vx), start}
            curr    = start

            for _ in range(arm):
                nbs = []
                cy, cx = curr
                for dy in [-1, 0, 1]:
                    for dx in [-1, 0, 1]:
                        if dy == 0 and dx == 0:
                            continue
                        ny, nx = cy+dy, cx+dx
                        if (ny, nx) not in visited:
                            if (0 <= ny < skel_slice.shape[0] and
                                    0 <= nx < skel_slice.shape[1]):
                                if skel_slice[ny, nx] > 0:
                                    nbs.append((ny, nx))
                if not nbs:
                    break
                curr = nbs[0]
                visited.add(curr)
                path.append(curr)

            branch_paths.append(path)

        if len(branch_paths) < 2:
            return None, None

        return branch_paths[0], branch_paths[1]


    def angle_between_branches(vertex_rc, branch1, branch2, sp_yx):
        vy, vx = vertex_rc
        v_mm   = np.array([vy * sp_yx[0], vx * sp_yx[1]])
        e1     = np.array([branch1[-1][0] * sp_yx[0], branch1[-1][1] * sp_yx[1]])
        e2     = np.array([branch2[-1][0] * sp_yx[0], branch2[-1][1] * sp_yx[1]])
        vec1   = e1 - v_mm
        vec2   = e2 - v_mm
        n1, n2 = np.linalg.norm(vec1), np.linalg.norm(vec2)
        if n1 < 1e-6 or n2 < 1e-6:
            return np.nan
        cos_a = np.clip(np.dot(vec1, vec2) / (n1 * n2), -1, 1)
        return float(np.degrees(np.arccos(cos_a)))


    # ---------- main loop ----------

    print("=" * 55)
    print(f"  {vessel_name} — Bifurcation Angle ({len(coordinates_dict)} slices)")
    print("=" * 55)

    results = []

    for sl_idx, vertex in coordinates_dict.items():
        skel_sl = skeleton_3d[sl_idx]
        result  = get_two_branches(skel_sl, vertex, arm=arm_dist)

        if result[0] is None or result[1] is None:
            print(f"  Slice {sl_idx}: WARNING — branches not found")
            results.append({
                "Slice":      sl_idx,
                "Vertex_row": vertex[0],
                "Vertex_col": vertex[1],
                "Angle_deg":  np.nan,
                "b1": None, "b2": None,
            })
            continue

        b1, b2 = result
        angle  = angle_between_branches(vertex, b1, b2, spacing_yx)

        print(f"  Slice {sl_idx}: vertex=({vertex[0]},{vertex[1]})"
              f"  ->  Angle = {angle:.1f} deg")
        results.append({
            "Slice":      sl_idx,
            "Vertex_row": vertex[0],
            "Vertex_col": vertex[1],
            "Angle_deg":  round(angle, 2),
            "b1": b1,
            "b2": b2,
        })

    valid = [r for r in results if not np.isnan(r["Angle_deg"])]
    best  = max(valid, key=lambda r: r["Angle_deg"]) if valid else None

    print("-" * 55)
    if best:
        print(f"  Best Slice: {best['Slice']}  |  Angle: {best['Angle_deg']:.1f} deg")
    else:
        print("  WARNING: No valid angle found")

    # ---------- visualization ----------

    n_slices = len(results)
    cols_n   = 4
    rows_n   = int(np.ceil(n_slices / cols_n))

    fig, axes = plt.subplots(rows_n, cols_n,
                              figsize=(cols_n*4, rows_n*4))
    axes = axes.flatten()

    for i, r in enumerate(results):
        ax = axes[i]
        sl = r["Slice"]
        vy = r["Vertex_row"]
        vx = r["Vertex_col"]

        pad  = 60
        r_lo = max(0, vy-pad);  r_hi = min(skeleton_3d[sl].shape[0], vy+pad)
        c_lo = max(0, vx-pad);  c_hi = min(skeleton_3d[sl].shape[1], vx+pad)

        ax.imshow(skeleton_3d[sl][r_lo:r_hi, c_lo:c_hi], cmap='gray',
                  extent=[c_lo, c_hi, r_hi, r_lo])

        angle = r["Angle_deg"]

        if not np.isnan(angle) and r["b1"] is not None:
            b1_arr = np.array(r["b1"])
            b2_arr = np.array(r["b2"])
            ax.plot(b1_arr[:,1], b1_arr[:,0], '-',
                    color='limegreen', lw=2, label='Branch 1 (ICA)')
            ax.plot(b2_arr[:,1], b2_arr[:,0], '-',
                    color='orange',    lw=2, label='Branch 2 (ECA)')
            ax.scatter([vx], [vy], c='red', s=120, zorder=6, marker='*')

            is_best     = (best is not None and sl == best["Slice"])
            title_color = 'gold'   if is_best else 'white'
            star        = " *BEST*" if is_best else ""
            ax.set_title(f"Slice {sl}{star}\n{angle:.1f} deg",
                         fontsize=10, fontweight='bold', color=title_color)
        else:
            ax.set_title(f"Slice {sl}\nFailed", fontsize=10, color='red')

        ax.set_xlim(c_lo, c_hi);  ax.set_ylim(r_hi, r_lo)
        ax.axis('off')

    for j in range(n_slices, len(axes)):
        axes[j].axis('off')

    best_info = (f"Slice {best['Slice']}  |  {best['Angle_deg']:.1f} deg"
                 if best else "Not found")
    plt.suptitle(f"{vessel_name} — Bifurcation Angle\nBest: {best_info}",
                 fontsize=13, fontweight='bold')
    plt.tight_layout()

    if output_path:
        out_png = os.path.join(output_path,
                               f"{vessel_name}_bifurcation_{n_slices}slices.png")
        plt.savefig(out_png, dpi=200, bbox_inches='tight')
        print(f"Saved: {out_png}")

    plt.show()

    if output_path:
        df_out = pd.DataFrame([{
            "Slice":      r["Slice"],
            "Vertex_row": r["Vertex_row"],
            "Vertex_col": r["Vertex_col"],
            "Angle_deg":  r["Angle_deg"],
        } for r in results])
        print("\n", df_out.to_string(index=False))
        xls = os.path.join(output_path,
                           f"{vessel_name}_bifurcation_{n_slices}slices.xlsx")
        df_out.to_excel(xls, index=False, engine='openpyxl')
        print(f"Saved: {xls}")

    return results, best


